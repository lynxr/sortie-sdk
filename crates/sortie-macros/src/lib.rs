//! Macros of the Sortie SDK, re-exported by `sortie`: use them as `#[sortie::mission]`,
//! `#[sortie::test(...)]` and `sortie::include_scenario!(...)`. Generated code only refers to
//! `::sortie::*` and `::core::*` paths.
//!
//! The expansion logic lives in modules over `proc_macro2` so it is unit-tested; the macros'
//! own compile errors are pinned by the trybuild tests in `tests/ui`. Errors whose text is
//! rustc's (the type checks behind `#[sortie::mission]`) are pinned by error code in the
//! `compile_fail` doctests of `sortie`, so a toolchain update does not break the tests.

use proc_macro::TokenStream;

mod mission;
mod scenario;
mod test_attr;

/// Marks the per-session entry point of a mission:
///
/// ```ignore
/// #[sortie::mission]
/// pub async fn run(ctx: Ctx<op_north::OpNorth>, start: Start) -> sortie::Result<()> { ... }
/// ```
///
/// The function is emitted unchanged, so it is what `sortie::main!(run)` takes (it accepts
/// any `sortie::runtime::Mission<M>`). Mistakes are reported at the definition, in two layers:
///
/// * the attribute checks the syntax: async, two arguments, no generics, an explicit return
///   type, and the types where they are spelled with the SDK's names (`Ctx<M>` first, `Start`
///   second, a `Result` return type that can be `sortie::Result<()>`; never `()`, a tuple or a
///   reference);
/// * once that passes, it asks the compiler to check the types (`Ctx<M>` with `M: Scenario`,
///   `Start`, `sortie::Result<()>`), which also covers aliases and other names.
#[proc_macro_attribute]
pub fn mission(attr: TokenStream, item: TokenStream) -> TokenStream {
    mission::expand(attr.into(), item.into()).into()
}

/// An async test driven by a harness, normally FakeDcs (`FakeDcs<M>`):
///
/// ```ignore
/// #[sortie::test(manifest = "fixtures/op_north.manifest.pb")]
/// async fn sam_goes_red(dcs: FakeDcs<OpNorth>) { ... }
/// ```
///
/// * `manifest` (optional) is relative to the directory of the crate's `Cargo.toml`
///   (`CARGO_MANIFEST_DIR`); `.pb` or `.json`. A missing file is a compile error at the literal.
/// * Expands to a plain `#[test] fn` that calls
///   `<FakeDcs<OpNorth> as ::sortie::testing::TestHarness>::run_test(manifest, body)`. The
///   harness builds the runtime (`current_thread`, `start_paused(true)`, `LocalSet`) and loads
///   the manifest.
/// * Other attributes (`#[should_panic]`, `#[ignore]`, docs) are kept; `#[test]` and
///   `#[tokio::test]` are rejected because the macro already adds `#[test]`.
///
/// Only with the feature `fake-dcs` (enabled by `sortie-fake`): FakeDcs is not part of Sortie
/// SDK 0.1, so without the feature the attribute is a compile error that says so.
#[proc_macro_attribute]
pub fn test(attr: TokenStream, item: TokenStream) -> TokenStream {
    if !cfg!(feature = "fake-dcs") {
        return test_attr::unavailable(item.into()).into();
    }
    let manifest_dir = std::env::var_os("CARGO_MANIFEST_DIR").map(std::path::PathBuf::from);
    test_attr::expand(attr.into(), item.into(), manifest_dir).into()
}

/// Includes the typed scenario module generated by `build.rs`:
///
/// ```ignore
/// // build.rs
/// fn main() { sortie_build::scenario("op_north", "../scenario.lock.json").emit(); }
/// // lib.rs
/// sortie::include_scenario!(op_north);   // pub mod op_north { pub struct OpNorth; ... }
/// ```
///
/// Reports a missing build script or a name that differs from the one given to
/// `sortie_build::scenario` at the call.
#[proc_macro]
pub fn include_scenario(input: TokenStream) -> TokenStream {
    let out_dir = std::env::var_os("OUT_DIR");
    match scenario::expand(input.into(), out_dir.as_deref()) {
        Ok(ts) => ts.into(),
        Err(e) => e.into_compile_error().into(),
    }
}
