"""Generate the Python protobuf and gRPC stubs of sortie-gen from the repository's proto/ tree.

    uv run python scripts/gen_proto.py            # (re)write src/sortie_gen/_proto
    uv run python scripts/gen_proto.py --check    # exit 1 if the committed stubs are stale
    uv run python scripts/gen_proto.py --out DIR  # write somewhere else (used by the tests)

The stubs are committed so that users of sortie-gen do not need grpcio-tools. protoc emits
absolute imports (``from sortie.v1 import common_pb2``); they are rewritten to live under
``sortie_gen._proto`` so the generated packages never shadow anything on ``sys.path``.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
PROTO_ROOT = (PROJECT / ".." / ".." / "proto").resolve()
DEFAULT_OUT = PROJECT / "src" / "sortie_gen" / "_proto"
PACKAGE = "sortie_gen._proto"

HEADER = '"""Generated by scripts/gen_proto.py from proto/. Do not edit."""\n'

_IMPORT_RE = re.compile(r"^(\s*)from sortie(\.[\w.]+)? import ", re.MULTILINE)
_PLAIN_IMPORT_RE = re.compile(r"^(\s*)import sortie\.", re.MULTILINE)


#: Packages the generator never speaks: the private bridge <-> engine link (``sortie.link``).
EXCLUDED = ("sortie/link/",)


def proto_files(root: Path = PROTO_ROOT) -> list[Path]:
    """The .proto files under ``root`` that the generator uses, sorted (stable protoc input order)."""
    return sorted(p for p in root.rglob("*.proto") if not p.relative_to(root).as_posix().startswith(EXCLUDED))


def _rewrite(text: str) -> str:
    text = _IMPORT_RE.sub(lambda m: f"{m.group(1)}from {PACKAGE}.sortie{m.group(2) or ''} import ", text)
    return _PLAIN_IMPORT_RE.sub(lambda m: f"{m.group(1)}import {PACKAGE}.sortie.", text)


def generate(out: Path, proto_root: Path = PROTO_ROOT) -> list[Path]:
    """Writes the stubs into ``out`` (replacing its contents) and returns the written files."""
    import grpc_tools
    from grpc_tools import protoc  # dev dependency only

    well_known = Path(grpc_tools.__file__).resolve().parent / "_proto"
    files = proto_files(proto_root)
    if not files:
        raise SystemExit(f"no .proto files under {proto_root}")
    with tempfile.TemporaryDirectory(prefix="sortie-gen-proto-") as tmp:
        raw = Path(tmp)
        args = [
            "grpc_tools.protoc",
            f"-I{proto_root}",
            f"-I{well_known}",
            f"--python_out={raw}",
            f"--pyi_out={raw}",
            f"--grpc_python_out={raw}",
            # Virtual paths relative to -I: protoc rejects "\" in them, even on Windows.
            *[f.relative_to(proto_root).as_posix() for f in files],
        ]
        code = protoc.main(args)
        if code != 0:
            raise SystemExit(f"protoc failed with exit code {code}")
        if out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True)
        written: list[Path] = []
        for src in sorted(raw.rglob("*")):
            if not src.is_file():
                continue
            dst = out / src.relative_to(raw)
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(_rewrite(src.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
            written.append(dst)
        # Regular packages (not namespace packages), so tools and importlib.resources see them.
        for d in sorted({out, *(p.parent for p in written)}):
            while True:
                init = d / "__init__.py"
                if not init.exists():
                    init.write_text(HEADER, encoding="utf-8", newline="\n")
                    written.append(init)
                if d == out:
                    break
                d = d.parent
        return sorted(written)


def diff(a: Path, b: Path) -> list[str]:
    """Relative paths that differ between two stub trees (missing on either side included)."""
    names_a = {p.relative_to(a).as_posix() for p in a.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
    names_b = {p.relative_to(b).as_posix() for p in b.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
    out = sorted(names_a ^ names_b)
    for name in sorted(names_a & names_b):
        # Line endings do not count: a Windows checkout may turn LF into CRLF.
        if _normalized(a / name) != _normalized(b / name):
            out.append(name)
    return sorted(out)


def _normalized(path: Path) -> bytes:
    return path.read_bytes().replace(b"\r\n", b"\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory")
    ap.add_argument("--check", action="store_true", help="only check that the committed stubs are current")
    args = ap.parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory(prefix="sortie-gen-check-") as tmp:
            fresh = Path(tmp) / "_proto"
            generate(fresh)
            stale = diff(fresh, args.out)
        if stale:
            print("stale protobuf stubs (run `uv run python scripts/gen_proto.py`):", file=sys.stderr)
            for name in stale:
                print(f"  {name}", file=sys.stderr)
            return 1
        print("protobuf stubs are up to date")
        return 0
    written = generate(args.out)
    print(f"wrote {len(written)} files to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
