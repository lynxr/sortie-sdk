"""The table ``sortie.static_type``: DCS static object types with their ``category`` and
``shape_name``, taken from the pydcs database.

A static table needs the right ``category`` / ``shape_name`` pair for its type, else DCS shows
nothing (and cannot report either at run time). The engine fills both from this table when a
``SpawnStatic`` leaves them empty and refuses a category that contradicts it. The table is
written to ``catalog/static_types.toml`` by ``scripts/gen_static_types.py``; this module only
renders it, so the tests can check that the committed file is current.

Rows: every static type of ``dcs.statics`` (fortifications, cargo, warehouses) with its
category and shape, the three heliport types of ``dcs.unit`` (category ``Heliports``), and the
aircraft, helicopter, ship and vehicle types of pydcs as statics (categories ``Planes``,
``Helicopters``, ``Ships``, ``Vehicles``; no shape: DCS takes the unit's model). Map object
classes without a category (``Building``, ``Bridge``, ...) are left out. Whether DCS 2.9.31
shows every row is not measured yet (live check OBJ-T30).
"""

from __future__ import annotations

import json
from importlib.metadata import version

#: Categories whose types are unit types (``Unit.getDescByName`` knows them).
UNIT_CATEGORIES = ("Planes", "Helicopters", "Ships", "Vehicles")

#: The heliport types of ``dcs.unit`` (``BaseFARP`` subclasses): type -> shape.
HELIPORTS = {
    "FARP": "FARPS",
    "SINGLE_HELIPAD": "FARP",
    "Invisible FARP": "invisiblefarp",
}

#: The command that writes both generated files (``--check`` only compares them).
COMMAND = "cd python/sortie-gen && UV_PYTHON_DOWNLOADS=never uv run --locked python scripts/gen_static_types.py"

#: Where the pydcs notice is written (next to the table; the runtime archive and the SDK
#: repository carry it in their THIRD-PARTY-NOTICES).
NOTICE_PATH = "catalog/THIRD-PARTY-pydcs.txt"

HOMEPAGE = "https://github.com/pydcs/dcs"


def _license_expression() -> str:
    from importlib.metadata import distribution

    meta = distribution("pydcs").metadata
    return meta.get("License-Expression") or meta.get("License") or "LGPL-3.0-or-later"


def header() -> str:
    """The comment block of ``catalog/static_types.toml``: what it is, where its facts come from
    and how it is made. Nothing of pydcs is copied into it but the facts of the rows."""
    return f"""\
# The table `sortie.static_type`: DCS static object types with the `category` and `shape_name`
# a static table needs (DCS cannot report either at run time, and a wrong pair is invisible).
# The engine uses both as defaults for SpawnStatic; whether DCS knows a type is decided by
# getDescByName on the running DCS, so a type missing here works when the caller sets both.
#
# Source: pydcs {version("pydcs")} ({HOMEPAGE}, PyPI package `pydcs`), license
# {_license_expression()}. Each row is three facts read from the installed package: the type
# name, its category and its shape name (static types of `dcs.statics.fortification_map`,
# `cargo_map` and `warehouse_map`; the unit type names of `dcs.planes.plane_map`,
# `dcs.helicopters.helicopter_map`, `dcs.ships.ship_map` and `dcs.vehicles.vehicle_map`, which
# need no shape), plus the three heliport types of `dcs.unit`. No code, comment or docstring of
# pydcs is in this file. The pydcs license text: {NOTICE_PATH}.
#
# Generated by python/sortie-gen/scripts/gen_static_types.py; never edit by hand. Regenerate:
#   {COMMAND}
# CI runs it with --check (the committed file must equal a fresh render). Not measured on DCS
# yet: live check OBJ-T30.
"""


def license_text() -> str:
    """The license text pydcs ships in its package metadata (``License-File``)."""
    from importlib.metadata import distribution

    dist = distribution("pydcs")
    names = dist.metadata.get_all("License-File") or []
    for f in dist.files or []:
        if f.name in names or f.name.upper().startswith(("LICENSE", "COPYING")):
            return f.read_text(encoding="utf-8").replace("\r\n", "\n")
    raise RuntimeError("the installed pydcs package carries no license file")


def render_notice() -> str:
    """The text of ``catalog/THIRD-PARTY-pydcs.txt`` (LF line endings)."""
    text = license_text().rstrip("\n")
    return f"""\
pydcs {version("pydcs")}
{"=" * (6 + len(version("pydcs")))}

Project:  {HOMEPAGE} (PyPI package `pydcs`)
License:  {_license_expression()}
Used for: catalog/static_types.toml (the table `sortie.static_type`) holds facts read from
          the pydcs database: type names of DCS static objects and unit types with their
          category and shape name. No pydcs code, comment or docstring is copied. The table
          is compiled into the engine (sortied) and published in the SDK repository.
          The scenario generator sortie-gen depends on the unmodified pydcs package, which
          pip / uv install from PyPI; it is not part of these files.
Made by:  python/sortie-gen/scripts/gen_static_types.py ({COMMAND}).

The license text as the installed package ships it ({", ".join(_license_files())}):

{text}
"""


def _license_files() -> list[str]:
    from importlib.metadata import distribution

    return distribution("pydcs").metadata.get_all("License-File") or ["LICENSE"]


def rows() -> dict[str, tuple[str, str]]:
    """type -> (category, shape) for every row of the table (shape "" = none)."""
    import dcs.helicopters
    import dcs.planes
    import dcs.ships
    import dcs.statics
    import dcs.vehicles

    out: dict[str, tuple[str, str]] = {}

    def put(type_name: str, category: str, shape: str) -> None:
        if type_name and category and type_name not in out:
            out[type_name] = (category, shape)

    for table in (dcs.statics.fortification_map, dcs.statics.cargo_map, dcs.statics.warehouse_map):
        for type_name, cls in sorted(table.items()):
            put(type_name, cls.category or "", cls.shape_name or "")
    for type_name, shape in sorted(HELIPORTS.items()):
        put(type_name, "Heliports", shape)
    for category, table in (
        ("Planes", dcs.planes.plane_map),
        ("Helicopters", dcs.helicopters.helicopter_map),
        ("Ships", dcs.ships.ship_map),
        ("Vehicles", dcs.vehicles.vehicle_map),
    ):
        for type_name in sorted(table):
            put(type_name, category, "")
    return out


def render() -> str:
    """The text of ``catalog/static_types.toml`` (LF line endings, sorted by type)."""
    lines = [header().rstrip("\n"), "", "version = 1", f"source = {json.dumps('pydcs ' + version('pydcs'))}", "", "[types]"]
    for type_name, (category, shape) in sorted(rows().items()):
        fields = [f"category = {json.dumps(category)}"]
        if shape:
            fields.append(f"shape = {json.dumps(shape)}")
        lines.append(f"{json.dumps(type_name)} = {{ {', '.join(fields)} }}")
    return "\n".join(lines) + "\n"
